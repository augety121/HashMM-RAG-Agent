def _safe_filename(name: str) -> str:
    return "".join(ch if (ch.isalnum() or ch == "_") else "_" for ch in name) + ".json"


def seed_builtin_content(log=None) -> dict:
    """逐条按名称幂等地补齐预置内容。返回 {templates: n, skills: n}（本次新增数）。"""
    out = {"templates": 0, "skills": 0}
    if os.environ.get("HASHMM_NO_SEED") == "1":
        return out
    _log = log or (lambda *_a: None)

    # 模板：只补「按名称缺失」的（已存在的绝不重复/覆盖）
    try:
        from hashmm.api import database as db
        existing_names = {t.get("name") for t in db.list_templates()}
        for name, cat, prompt, variables in BUILTIN_TEMPLATES:
            if name in existing_names:
                continue
            db.create_template(name, cat, prompt, variables, author="builtin")
            out["templates"] += 1
        if out["templates"]:
            _log(f"[seed] 补齐预置模板 {out['templates']} 个")
    except Exception as e:
        _log(f"[seed] 模板种子跳过: {e}")

    # 手动技能：只补「文件不存在」的（与管理后台手动创建同一存储格式）
    try:
        skills_dir = Path("data/skills")
        skills_dir.mkdir(parents=True, exist_ok=True)
        for s in BUILTIN_SKILLS:
            fpath = skills_dir / _safe_filename(s["name"])
            if fpath.exists():
                continue
            fpath.write_text(json.dumps(s, ensure_ascii=False, indent=2), encoding="utf-8")
            out["skills"] += 1
        if out["skills"]:
            _log(f"[seed] 补齐预置技能 {out['skills']} 个")
    except Exception as e:
        _log(f"[seed] 技能种子跳过: {e}")

    # V200: 内置技能同时写入 DB skills 表 —— 聊天用的 skill_manager 从 DB 读、不读 data/skills 文件。
    # 之前技能只写到文件，导致普通对话完全用不上。这里按 name 幂等补入 DB，不动已学习/已有技能。
    try:
        from hashmm.api import database as _db
        from hashmm.evolution.skill_manager import get_skill_manager as _get_skill_manager
        import uuid as _uuid, time as _time
        # Run the authoritative migration before seeding; a local CREATE TABLE
        # copy would otherwise omit owner/scope columns and silently turn
        # built-ins into untrusted legacy rows.
        _get_skill_manager()._ensure_table()
        with _db._conn() as c:
            for s in BUILTIN_SKILLS:
                if c.execute("SELECT 1 FROM skills WHERE name=?", (s["name"],)).fetchone():
                    continue
                c.execute(
                    "INSERT INTO skills (id,name,description,trigger_patterns,prompt_template,examples,quality_score,use_count,created_at,last_used,owner_id,scope,workspace_id) "
                    "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)",
                    ("builtin-" + _uuid.uuid4().hex[:12], s["name"], s.get("description", ""),
                     json.dumps(s.get("triggers", []), ensure_ascii=False),
                     s.get("prompt", ""), json.dumps([]), 0.8, 0, _time.time(), 0,
                     "", "builtin", ""),
                )
                out["skills_db"] = out.get("skills_db", 0) + 1
        if out.get("skills_db"):
            _log(f"[seed] 内置技能入库 {out['skills_db']} 个")
            try:  # 让聊天用的 skill_manager 重新从 DB 加载，立即生效
                from hashmm.evolution.skill_manager import get_skill_manager
                _m = get_skill_manager(); _m._loaded = False; _m._skills = []
            except Exception:
                pass
    except Exception as e:
        _log(f"[seed] 技能入库跳过: {e}")
    return out
